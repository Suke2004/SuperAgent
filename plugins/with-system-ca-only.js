/**
 * Trust only the CAs that shipped with the device, not the ones someone added.
 *
 * Android's default trust store is "system CAs plus whatever the user installed",
 * which is what makes an interception proxy work: install its root, and every app
 * that has not opted out sees a valid certificate. This app sends a Bearer token to
 * the gateway on every request, so on a phone with a corporate MDM profile or a
 * developer's own mitmproxy root the key is readable in plaintext by whoever runs
 * that proxy — and nothing in the app would look wrong.
 *
 * Excluding the user store closes that. It is not certificate pinning and is not
 * meant to be: pinning a leaf or an intermediate we do not control means the app
 * stops working the day the gateway rotates its certificate, which is a self-inflicted
 * outage traded against an attacker who has to get a *system* CA to mis-issue. This
 * is the part of pinning that costs nothing to keep correct.
 *
 * `<debug-overrides>` puts the user store back for debuggable builds only, because
 * inspecting one's own traffic during development is a legitimate thing to do and
 * Android drops that block from release builds outright.
 *
 * Cleartext is refused in the release config and permitted in the debug one, which is
 * why there are two files rather than one. The app's own base URLs are `https` by the
 * profile editor's validation, so nothing it sends needs cleartext — but a network
 * security config that permits it is a standing allowance for anything else in the
 * process, and "HTTPS only" should be true of the platform and not only of our own
 * URL parser. Metro talks to a debug build over plain HTTP, so the debug source set
 * overrides the same resource name with `cleartextTrafficPermitted="true"`; AGP
 * resolves `src/debug/res` over `src/main/res` for a debuggable variant, and the file
 * is absent from a release APK entirely.
 *
 * `expo/config-plugins` rather than `@expo/config-plugins`, for the reason
 * `with-no-backup.js` gives.
 */
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const header = '<!-- Generated by plugins/with-system-ca-only.js. Edits here are lost on the next prebuild. -->';

const config_ = (cleartext, userCas) => `<?xml version="1.0" encoding="utf-8"?>
${header}
<network-security-config>
    <base-config cleartextTrafficPermitted="${cleartext}">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <debug-overrides>
        <trust-anchors>
            <certificates src="system" />${userCas ? '\n            <certificates src="user" />' : ''}
        </trust-anchors>
    </debug-overrides>
</network-security-config>
`;

module.exports = function withSystemCaOnly(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const write = (sourceSet, contents) => {
        const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src', sourceSet, 'res/xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, 'network_security_config.xml'), contents, 'utf8');
      };
      write('main', config_(false, true));
      write('debug', config_(true, true));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0];
    if (!application) throw new Error('with-system-ca-only: no <application> in AndroidManifest.xml');
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
};

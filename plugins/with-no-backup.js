/**
 * Keep the conversation database out of every Android backup path.
 *
 * `android.allowBackup: false` in app.json closes the old one (Auto Backup to the
 * user's Google Drive). It is not enough on its own: from Android 12 the
 * device-to-device transfer that runs when someone sets up a new phone ignores
 * `allowBackup` and is governed only by `android:dataExtractionRules`. Without a
 * rules file the default is "copy everything", which means the plaintext SQLite
 * file — every message, and base64 attachment bytes in its cells — plus all of
 * AsyncStorage would ride across to the new device, while the Keystore-held API
 * key would not. That asymmetry is the whole problem: the data moves, the secret
 * that was supposed to gate it does not.
 *
 * So: exclude everything from both channels. There is nothing in this app worth
 * restoring that is not already covered by Settings → Backup, which the user
 * drives explicitly and which redacts on the way out.
 *
 * `expo/config-plugins` rather than `@expo/config-plugins`: under pnpm the latter
 * is not resolvable from the project root, the subpath export is.
 */
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/** Both channels, everything excluded. `cloudBackup` still matters for < 12. */
const RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-no-backup.js. Edits here are lost on the next prebuild. -->
<data-extraction-rules>
    <cloud-backup>
        <exclude domain="root" />
        <exclude domain="database" />
        <exclude domain="sharedpref" />
        <exclude domain="file" />
        <exclude domain="external" />
    </cloud-backup>
    <device-transfer>
        <exclude domain="root" />
        <exclude domain="database" />
        <exclude domain="sharedpref" />
        <exclude domain="file" />
        <exclude domain="external" />
    </device-transfer>
</data-extraction-rules>
`;

module.exports = function withNoBackup(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'data_extraction_rules.xml'), RULES, 'utf8');
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0];
    if (!application) throw new Error('with-no-backup: no <application> in AndroidManifest.xml');
    // Set here as well as via app.json's `allowBackup` so the guarantee does not
    // depend on two files agreeing.
    application.$['android:allowBackup'] = 'false';
    application.$['android:dataExtractionRules'] = '@xml/data_extraction_rules';
    return cfg;
  });
};
